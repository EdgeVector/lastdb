#!/usr/bin/env python3
"""Generate the SDK app API types from lastdb_node/app-api.json.

--write regenerates lastdb_app_sdk/src/appApi.generated.ts.
--check fails when that file differs. No third-party packages.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP_API = "lastdb_node/app-api.json"
OUT = "lastdb_app_sdk/src/appApi.generated.ts"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
ALLOWED = {
    "$ref", "type", "enum", "const", "minimum", "maximum", "minItems", "maxItems",
    "items", "required", "properties", "additionalProperties", "oneOf", "anyOf",
    "description", "title", "default", "nullable",
}
TYPES = {"null", "boolean", "integer", "number", "string", "array", "object"}
LIMITS = {
    "reads_per_request": "APP_API_READS_PER_REQUEST",
    "read_page_default": "APP_API_READ_PAGE_DEFAULT",
    "read_page_cap": "APP_API_READ_PAGE_CAP",
    "changes_page_default": "APP_API_CHANGES_PAGE_DEFAULT",
    "changes_page_cap": "APP_API_CHANGES_PAGE_CAP",
    "changes_kept": "APP_API_CHANGES_KEPT",
    "manifest_access_entries": "APP_API_MANIFEST_ACCESS_ENTRIES",
}
NAMED_ENUM = {("Error", "code"): "ErrorCode", ("Error", "reason"): "ErrorReason"}
HEADER = (
    "// GENERATED by scripts/lints/app_api_types.py --write. Do not edit.\n"
    "// Source: lastdb_node/app-api.json.\n"
    "// Regenerate: python3 scripts/lints/app_api_types.py --write\n"
)
SIZE_OK = (
    "// lint:file-size-ok generated from lastdb_node/app-api.json; one type per schema\n"
)


def fail(where, message):
    raise SystemExit(f"app-api-types: {where}: {message}")


def ref_name(ref, path):
    prefix = "#/components/schemas/"
    name = ref[len(prefix):] if isinstance(ref, str) and ref.startswith(prefix) else ""
    if not name or "/" in name:
        fail(path, f"$ref is not a schema in this file: {ref!r}")
    return name


def walk(schema, path):
    """Reject a JSON Schema keyword this generator does not know."""
    if not isinstance(schema, dict):
        fail(path, "schema is not an object")
    for key in schema:
        if str(key).startswith("x-") or key in ALLOWED:
            continue
        fail(path, f"unsupported keyword {key}")
    if "$ref" in schema:
        for key in schema:
            if key in ("$ref", "description", "title") or str(key).startswith("x-"):
                continue
            fail(path, f"$ref combined with {key}")
        return
    if "oneOf" in schema and "anyOf" in schema:
        fail(path, "both oneOf and anyOf")
    if "nullable" in schema and not isinstance(schema["nullable"], bool):
        fail(path, "nullable is not a boolean")
    props = schema.get("properties")
    if isinstance(props, dict):
        for name, sub in props.items():
            walk(sub, f"{path}.{name}")
    elif "properties" in schema:
        fail(path, "properties is not an object")
    if "items" in schema:
        if not isinstance(schema["items"], dict):
            fail(path, "items must be one schema")
        walk(schema["items"], path + "/items")
    additional = schema.get("additionalProperties")
    if isinstance(additional, dict):
        walk(additional, path + "/additionalProperties")
    for key in ("oneOf", "anyOf"):
        branches = schema.get(key)
        if branches is None:
            continue
        if not isinstance(branches, list) or not branches:
            fail(path, f"{key} must be a non-empty list")
        for index, branch in enumerate(branches):
            walk(branch, f"{path}/{key}/{index}")


def escape(text):
    return text.replace("\\", "\\\\").replace("'", "\\'")


def literal(value, path):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return "'" + escape(value) + "'"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    fail(path, f"cannot render literal {value!r}")


def comment(schema):
    parts = []
    for key in ("description", "title"):
        value = schema.get(key)
        if isinstance(value, str) and value.strip():
            parts.append(" ".join(value.split()))
    notes = []
    if schema.get("type") == "integer":
        notes.append("Integer.")
    if "minimum" in schema:
        notes.append(f"Minimum {schema['minimum']}.")
    if "maximum" in schema:
        notes.append(f"Maximum {schema['maximum']}.")
    if "minItems" in schema:
        notes.append(f"Minimum items {schema['minItems']}.")
    if "maxItems" in schema:
        notes.append(f"Maximum items {schema['maxItems']}.")
    if "default" in schema:
        notes.append("Default " + json.dumps(schema["default"], ensure_ascii=True) + ".")
    if notes:
        parts.append(" ".join(notes))
    return " ".join(parts).replace("*/", "* /")


def prop_type(parent, name, schema):
    named = NAMED_ENUM.get((parent, name))
    if named:
        if "enum" not in schema:
            fail(f"{parent}.{name}", "expected an enum")
        return named
    return render_type(schema, f"{parent}.{name}")


def render_type(schema, path):
    if "$ref" in schema:
        return ref_name(schema["$ref"], path)
    if "oneOf" in schema or "anyOf" in schema:
        key = "oneOf" if "oneOf" in schema else "anyOf"
        parts = []
        for index, branch in enumerate(schema[key]):
            if isinstance(branch, dict) and "properties" in branch and "$ref" not in branch:
                fail(path, f"{key} branch {index} is an inline object; give it a schema name")
            parts.append(render_type(branch, f"{path}/{key}/{index}"))
        return " | ".join(parts)
    if "const" in schema:
        return literal(schema["const"], path)
    if "enum" in schema:
        if not isinstance(schema["enum"], list) or not schema["enum"]:
            fail(path, "enum must be a non-empty list")
        return " | ".join(literal(value, path) for value in schema["enum"])
    if "type" not in schema:
        fail(path, "no type, $ref, oneOf, anyOf, enum, or const")
    names = schema["type"] if isinstance(schema["type"], list) else [schema["type"]]
    if any(not isinstance(name, str) or name not in TYPES for name in names):
        fail(path, f"unknown type {schema['type']!r}")
    if len(names) > 1 and set(names) & {"object", "array"}:
        fail(path, f"cannot turn type {schema['type']!r} into one TypeScript type")
    bits = [scalar(name, schema, path) for name in names]
    if schema.get("nullable") is True and "null" not in names:
        bits.append("null")
    return " | ".join(bits)


def scalar(name, schema, path):
    if name in ("integer", "number"):
        return "number"
    if name == "array":
        item = render_type(schema["items"], path + "/items")
        return f"({item})[]" if "|" in item else f"{item}[]"
    if name == "object":
        return inline_object(schema, path)
    return name


def index_signature(schema, path):
    if "additionalProperties" not in schema:
        return "[key: string]: unknown"
    additional = schema["additionalProperties"]
    if additional is False:
        return None if schema.get("properties") else "[key: string]: never"
    if additional is True:
        return "[key: string]: unknown"
    if isinstance(additional, dict):
        if schema.get("properties"):
            fail(path, "properties combined with an additionalProperties schema")
        typ = render_type(additional, path + "/additionalProperties")
        if "|" in typ:
            typ = f"({typ})"
        return f"[key: string]: {typ}"
    fail(path, "additionalProperties is not a boolean or a schema")


def inline_object(schema, path):
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    bits = []
    for name, sub in props.items():
        if not isinstance(name, str) or not IDENT.match(name):
            fail(path, f"property {name!r} is not an identifier")
        mark = "" if name in required else "?"
        bits.append(f"{name}{mark}: {prop_type(path, name, sub)}")
    extra = index_signature(schema, path)
    if extra:
        bits.append(extra)
    if not bits:
        fail(path, "empty object")
    return "{ " + "; ".join(bits) + " }"


def plain_object(schema):
    if any(key in schema for key in ("$ref", "oneOf", "anyOf", "enum", "const")):
        return False
    kind = schema.get("type")
    return kind == "object" or (kind is None and ("properties" in schema or "additionalProperties" in schema))


def field_lines(schema, path, nevers):
    props = schema.get("properties") or {}
    required = schema.get("required") or []
    if not isinstance(required, list):
        fail(path, "required is not a list")
    lines = []
    for name, sub in props.items():
        if not isinstance(name, str) or not IDENT.match(name) or not isinstance(sub, dict):
            fail(path, f"property {name!r} is not an identifier with a schema")
        doc = comment(sub)
        if doc:
            lines.append(f"  /** {doc} */")
        mark = "" if name in required else "?"
        lines.append(f"  {name}{mark}: {prop_type(path, name, sub)};")
    for name in nevers:
        lines.append(f"  {name}?: never;")
    extra = index_signature(schema, path)
    if extra:
        lines.append(f"  {extra};")
    if not lines:
        fail(path, "empty object")
    return lines


def never_map(schemas):
    """Closed oneOf members that share a property reject each other's other fields.

    Disjoint shapes, such as a records page or an error, stay a plain union.
    """
    found = {name: [] for name in schemas}
    for owner, schema in schemas.items():
        branches = schema.get("oneOf")
        if not isinstance(branches, list):
            continue
        members, props = [], {}
        for index, branch in enumerate(branches):
            if not (isinstance(branch, dict) and "$ref" in branch):
                continue
            member = ref_name(branch["$ref"], f"{owner}/oneOf/{index}")
            target = schemas.get(member)
            if target is None:
                fail(owner, f"unknown schema {member}")
            if target.get("additionalProperties") is not False:
                continue
            members.append(member)
            props[member] = list(target.get("properties") or {})
        if len(members) < 2 or not set.intersection(*(set(props[name]) for name in members)):
            continue
        for member in members:
            own = set(props[member])
            for other, names in props.items():
                if other == member:
                    continue
                for name in names:
                    if name not in own and name not in found[member]:
                        found[member].append(name)
    return found


def emit_schema(name, schema, nevers):
    if not IDENT.match(name):
        fail(name, "schema name is not a TypeScript identifier")
    doc = comment(schema)
    head = f"/** {doc} */\n" if doc else ""
    if plain_object(schema):
        body = "\n".join(field_lines(schema, name, nevers))
        return f"{head}export interface {name} {{\n{body}\n}}"
    return f"{head}export type {name} = {render_type(schema, name)};"


def number_const(name, value, doc):
    if isinstance(value, bool) or not isinstance(value, int):
        fail(name, f"expected an integer, got {value!r}")
    return f"/** {doc} */\nexport const {name} = {value};"


def string_list(const, alias, values, doc):
    if not isinstance(values, list) or not values or any(not isinstance(item, str) for item in values):
        fail(const, "expected a non-empty list of strings")
    inner = ",\n".join("  '" + escape(item) + "'" for item in values)
    return (
        f"/** {doc} */\nexport const {const} = [\n{inner},\n] as const;\n\n"
        f"/** One value of `{const}`. */\nexport type {alias} = (typeof {const})[number];"
    )


def render_limits(document):
    limits = document.get("x-lastdb-limits")
    if not isinstance(limits, dict):
        fail("x-lastdb-limits", "missing object")
    unknown = [key for key in limits if key not in LIMITS]
    missing = [key for key in LIMITS if key not in limits]
    if unknown:
        fail("x-lastdb-limits", "no constant for " + ", ".join(unknown))
    if missing:
        fail("x-lastdb-limits", "missing " + ", ".join(missing))
    lines = [
        number_const(LIMITS[key], value, f"`x-lastdb-limits.{key}` in lastdb_node/app-api.json.")
        for key, value in limits.items()
    ]
    lines.append(number_const(
        "APP_API_MAX_BODY_BYTES",
        document.get("x-lastdb-app-socket-max-body-bytes"),
        "`x-lastdb-app-socket-max-body-bytes` in lastdb_node/app-api.json.",
    ))
    return "\n\n".join(lines)


def render_enums(document):
    try:
        props = document["components"]["schemas"]["Error"]["properties"]
        code, reason = props["code"]["enum"], props["reason"]["enum"]
    except (KeyError, TypeError) as error:
        fail("Error", f"code and reason enums are required ({error})")
    return "\n\n".join((
        string_list("APP_API_ERROR_CODES", "ErrorCode", code, "Codes of `Error.properties.code`."),
        string_list("APP_API_ERROR_REASONS", "ErrorReason", reason, "Reasons of `Error.properties.reason`."),
    ))


def line_count(text):
    return text.count("\n") + (0 if text.endswith("\n") or not text else 1)


def generate(document):
    schemas = document["components"]["schemas"]
    nevers = never_map(schemas)
    parts = [HEADER.rstrip("\n"), "", render_limits(document), "", render_enums(document), ""]
    for name, schema in schemas.items():
        parts.append(emit_schema(name, schema, nevers.get(name, [])))
        parts.append("")
    text = "\n".join(parts).rstrip() + "\n"
    if line_count(text) > 400:
        text = text.replace(HEADER, HEADER + SIZE_OK, 1)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the SDK file")
    mode.add_argument("--check", action="store_true", help="fail when the SDK file differs")
    args = parser.parse_args()
    try:
        document = json.loads((ROOT / APP_API).read_text())
    except (OSError, json.JSONDecodeError) as error:
        fail(APP_API, str(error))
    schemas = (document.get("components") or {}).get("schemas")
    if not isinstance(schemas, dict) or not schemas:
        fail("components.schemas", "missing")
    for name, schema in schemas.items():
        walk(schema, str(name))
    text = generate(document)
    dest = ROOT / OUT
    if args.write:
        dest.write_text(text)
        print(f"app-api-types: wrote {OUT}")
        return 0
    if not dest.is_file() or dest.read_text() != text:
        print(
            f"app-api-types: FAIL {OUT} is out of date; run: python3 scripts/lints/app_api_types.py --write",
            file=sys.stderr,
        )
        return 1
    print(f"app-api-types: OK schemas={len(schemas)} lines={line_count(text)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
